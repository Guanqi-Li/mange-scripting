"""Build a self-contained Scripting module without network dependencies."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=json.loads((root/'sources/guazi.json').read_text(encoding='utf-8-sig'))
# jsoup accepts unquoted attribute values containing slashes; CSS DOM does not.
for group,field in [('search','link'),('detail','chapters')]:
 source[group][field]=source[group][field].replace('href^=/comic.php','href^="/comic.php"').replace('href^=/chapter.php','href^="/chapter.php"')
(root/'sources/guazi.json').write_text(json.dumps(source,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
app='const DEFAULT_SOURCE = '+json.dumps(source,ensure_ascii=False)+';\n'+(root/'app.ts').read_text(encoding='utf-8-sig')
html=(root/'shell.html').read_text(encoding='utf-8-sig').replace('__APP__',app.replace('</script','<\\/script'))
(root/'ui.ts').write_text('// Generated by tools/build.py\nexport const html = '+json.dumps(html,ensure_ascii=False)+'\n',encoding='utf-8')
print('Built ui.ts')
